/** 按 id 查部门;找不到抛错(数据错误应尽早暴露)。 */
export function getDeptById(id: string): Dept {
  const dept = DEPARTMENTS.find((d) => d.id === id);
  if (!dept) throw new Error(`Unknown department id: ${id}`);
  return dept;
}
