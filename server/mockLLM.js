/** 生成 mock 回复;相同 prompt 稳定,不同 step/历史变化。 */
function mockGenerate(prompt) {
  if (prompt.includes('官途开局背景')) {
    return [
      '【行政级别】县级',
      '【入职方式】省考招录(笔试第3名)',
      '【家庭背景】普通家庭,父母是教师',
      '【开场白】你拖着行李箱站在单位门口,门卫核对了三遍报到证才笑着指了指三楼。科长递给你一杯浓茶:"先把近三年的档案看一遍。"窗外的梧桐叶落了一地,你的官途从这摞泛黄的档案开始。',
      '【初始职务】综合科科员',
    ].join('\n');
  }
  const stepMatch = prompt.match(/第(\d+)步/);
  const step = stepMatch ? parseInt(stepMatch[1], 10) : 1;
  // 场景按步数轮转:一局 24 步取到 30 个场景中互不相同的 24 个。
  const scene = SCENE_BANK[(step - 1) % SCENE_BANK.length];
  const lastTitle = (prompt.match(/标题[:：](.+)/) || [])[1];
  const lines = [
    `【事件类型】${scene.tag}`,
    `【类型标签】${scene.tagLabel}`,
    `【事件标题】${scene.title}`,
    // 衔接只回引真实存在的上一步标题,不捏造人物。
    `【剧情衔接】${lastTitle ? `承接「${lastTitle.trim()}」的余波,事情还没完。` : '这是你入职后的第一件事。'}`,
    `【事件描述】${scene.desc}`,
    `【出场人物】${scene.npc};办公室同事小刘(科员)`,
    `【官场格言】${scene.hint}`,
  ];
  const ci = (step - 1 + CHOICE_BANK[0].length) % CHOICE_BANK[0].length;
  for (let i = 0; i < 4; i++) {
    const letter = 'ABCD'[i];
    const eff = scene.effects[i];
    const text = CHOICE_BANK[i][ci];
    lines.push(`【选项${letter}】${text}`);
    lines.push(`【选项${letter}提示】${letter === 'A' ? '稳妥但费工' : letter === 'B' ? '程序优先' : letter === 'C' ? '经营关系' : '省事但有代价'}`);
    lines.push(
      `【选项${letter}效果】政治嗅觉:${eff[0]} 执行力:${eff[1]} 人脉资源:${eff[2]} 廉洁度:${eff[3]} 晋升:0`,
    );
  }
  return lines.join('\n');
}

module.exports = { mockGenerate, SCENE_BANK, CHOICE_BANK };
